"""Write docs/evaluation/results.md from the stored evaluation runs.

    jobmarket eval report --run <id> [--run <id> ...]

The first run is the accepted configuration; the others are compared with it.
The data-quality experiment is included when eval/results/data_quality_experiment.json exists.
"""

from __future__ import annotations

import json
from pathlib import Path

from jobmarket.evaluation.runner import RESULTS_DIR, load_eval_set
from jobmarket.settings import REPO_ROOT

REPORT = REPO_ROOT / "docs" / "evaluation" / "results.md"

THRESHOLDS = {  # Evaluation Plan section 4
    "routing_accuracy": (">=", 0.90),
    "analytical_accuracy": (">=", 0.90),
    "recall_at_5": (">=", 0.80),
    "duplicate_at_5": ("<=", 0.05),
    "stale_at_5": ("<=", 0.02),
    "citation_accuracy": (">=", 0.95),
    "groundedness": (">=", 0.90),
    "correct_refusal_rate": (">=", 1.0),
}
LABELS = {
    "routing_accuracy": "Routing accuracy",
    "analytical_accuracy": "Analytical accuracy",
    "recall_at_5": "Recall@5",
    "mrr": "MRR",
    "duplicate_at_5": "Duplicate rate@5",
    "stale_at_5": "Stale rate@5",
    "citations_relevant": "Cited postings relevant",
    "citation_accuracy": "Citation accuracy (judge)",
    "groundedness": "Groundedness (judge)",
    "correct_refusal_rate": "Correct refusal rate",
    "false_refusal_rate": "False refusal rate",
    "resume_skill_precision": "Resume skill precision",
    "resume_skill_recall": "Resume skill recall",
    "latency_p50_ms": "Latency p50 (ms)",
    "latency_p95_ms": "Latency p95 (ms)",
    "tokens_per_question": "Tokens per question",
}


def _fmt(metric: str, value) -> str:
    if value is None:
        return "\u2013"
    if metric.endswith("_ms") or metric.startswith("tokens"):
        return f"{int(value):,}"
    return f"{value:.0%}" if metric != "mrr" else f"{value:.2f}"


def _verdict(metric: str, value) -> str:
    if metric not in THRESHOLDS or value is None:
        return ""
    op, target = THRESHOLDS[metric]
    ok = value >= target if op == ">=" else value <= target
    return f"{'met' if ok else '**not met**'} ({op} {_fmt(metric, target)})"


def _load(run_id: str) -> dict:
    return json.loads((RESULTS_DIR / f"{run_id}.json").read_text())


def write_report(run_ids: list[str], path: Path = REPORT) -> Path:
    runs = [_load(r) for r in run_ids]
    main = runs[0]
    snap = main["config"]["snapshot"]
    lines = [
        "# Evaluation Results",
        "",
        "Generated by `jobmarket eval report` from the stored runs in `eval/results/`. The method,",
        "question set and thresholds are in the [Evaluation Plan](../requirements/evaluation_plan.md).",
        "",
        "## Accepted configuration",
        "",
        "| | |",
        "|---|---|",
        f"| **Run** | `{main['run_id']}` |",
        f"| **Answering and routing model** | `{main['config']['llm']}` |",
        f"| **Embedding model** | `{main['config']['embedding']}` |",
        f"| **Judge** | `{main['config']['judge']}` |",
        f"| **Chunker / prompts** | `{main['config']['chunker_version']}` / `{main['config']['prompt_version']}` |",
        f"| **Commit** | `{main['config']['commit']}` |",
        f"| **Data snapshot** | {snap.get('jobs')} jobs, last seen {snap.get('last_seen_at', '')[:16]} |",
        f"| **Questions** | {main['summary']['questions']} |",
        "",
        "| Metric | Result | Threshold |",
        "|---|---|---|",
    ]
    for metric, label in LABELS.items():
        value = main["summary"].get(metric)
        lines.append(f"| {label} | {_fmt(metric, value)} | {_verdict(metric, value)} |")

    if len(runs) > 1:
        lines += ["", "## Comparison", "", "| Metric | " + " | ".join(f"`{r['run_id']}`" for r in runs) + " |"]
        lines.append("|---|" + "---|" * len(runs))
        lines.append(
            "| Model | "
            + " | ".join(f"`{r['config']['llm']}`, `{r['config']['embedding'].split(':')[-1]}`" for r in runs)
            + " |"
        )
        for metric, label in LABELS.items():
            lines.append(f"| {label} | " + " | ".join(_fmt(metric, r["summary"].get(metric)) for r in runs) + " |")

    experiment = RESULTS_DIR / "data_quality_experiment.json"
    if experiment.exists():
        exp = json.loads(experiment.read_text())
        lines += [
            "",
            "## Data-quality experiment",
            "",
            f"Retrieval only (no language model), {len(exp['questions'])} semantic questions, `{exp['embedding']}`.",
            "Each run changes one thing; see the "
            "[Evaluation Plan](../requirements/evaluation_plan.md#5-data-quality-experiment).",
            "",
            "| Run | Change | Recall@5 | MRR | Duplicate rate@5 | Stale rate@5 | Recall@5, filtered questions |",
            "|---|---|---|---|---|---|---|",
        ]
        changes = {
            "A": "Every posting indexed (reposts and cross-source copies), vector search, no filters",
            "B": "A + deduplication: one entry per job",
            "C": "B + closed postings excluded",
            "D": "C + metadata filters from the router",
            "E": "D + hybrid keyword and vector search",
        }
        for name, s in exp["summary"].items():
            lines.append(
                f"| {name} | {changes[name]} | {_fmt('r', s['recall_at_5'])} | {s['mrr']:.2f} | "
                f"{_fmt('d', s['duplicate_at_5'])} | {_fmt('s', s['stale_at_5'])} | "
                f"{_fmt('r', s['recall_at_5_filtered_questions'])} |"
            )

    embeddings = RESULTS_DIR / "embedding_comparison.json"
    if embeddings.exists():
        emb = json.loads(embeddings.read_text())
        lines += [
            "",
            "## Embedding models",
            "",
            f"Retrieval only, {emb['questions']} questions, the router's plans from "
            f"`{emb['baseline_run']}`, hybrid search with filters.",
            "",
            "| Model | Dimensions | Recall@5 | MRR | Recall@5, vector only, no filters | Query embedding p50 |",
            "|---|---|---|---|---|---|",
        ]
        for name, e in emb["summary"].items():
            lines.append(
                f"| `{name}` | {e['dimensions']} | {e['recall_at_5']:.1%} | {e['mrr']:.2f} | "
                f"{e['recall_at_5_vector_only_unfiltered']:.1%} | {e['query_embedding_ms_p50']} ms |"
            )

    findings = REPO_ROOT / "eval" / "findings.md"
    if findings.exists():
        lines += ["", findings.read_text().strip()]

    questions = {q["id"]: q for q in load_eval_set()}
    misses = [
        r
        for r in main["rows"]
        if r.get("route_correct") is False
        or r.get("analytical_correct") is False
        or r.get("error")
        or (r.get("expected_route") == "unanswerable" and not r.get("refused"))
    ]
    lines += ["", "## Questions the accepted run got wrong", ""]
    if not misses:
        lines.append("None.")
    else:
        lines += ["| Question | Expected | Got | Why |", "|---|---|---|---|"]
        for r in misses:
            why = r.get("error") or ("wrong figures" if r.get("analytical_correct") is False else "wrong route")
            q = questions.get(r["id"], {}).get("question", "")
            lines.append(f"| {r['id']}: {q} | {r.get('expected_route')} | {r.get('route')} | {why} |")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    return path
